create or replace function public.test_seed_shift(uid uuid,hours_ago integer default 8)
returns bigint language plpgsql as $$
declare s timestamptz:=date_trunc('minute',clock_timestamp()-make_interval(hours=>hours_ago)); ms bigint;
begin
  ms:=floor(extract(epoch from s)*1000);
  insert into public.active_time_sessions(auth_user_id,employee_pin,employee_name,department,started_at,started_at_ms,clock_in_location)
    select uid,uid::text,employee_name,department,s,ms,'Test shop' from public.app_users where auth_user_id=uid;
  return ms;
end $$;

