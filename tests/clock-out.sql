create or replace function private.gp_is_admin() returns boolean language sql security definer set search_path='' as $$
  select exists(select 1 from public.app_users where auth_user_id=auth.uid() and active is true and perm_admin is true and archived_at is null);
$$;
create or replace function private.gp_has_permission(p text) returns boolean language sql security definer set search_path='' as $$
  select exists(select 1 from public.app_users where auth_user_id=auth.uid() and active is true and archived_at is null and (perm_admin is true or (p='time' and perm_time is true)));
$$;
