create or replace function public.test_assert(condition boolean,label text) returns void language plpgsql as $$
begin if condition is not true then raise exception 'FAILED: %',label; end if; end $$;
create or replace function public.test_expect_error(q text,needle text) returns void language plpgsql as $$
begin
  begin execute q;
  exception when others then
    if position(lower(needle) in lower(sqlerrm))=0 then raise exception 'Unexpected error: %; expected %',sqlerrm,needle; end if;
    return;
  end;
  raise exception 'FAILED: statement should have rejected: %',needle;
end $$;
